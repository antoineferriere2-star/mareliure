/**
 * Generic Project Brief (Dossier Commercial) generator. Walks a
 * PlaybookSchema's briefConfig + per-field briefMapping against a set of
 * answers and produces the canonical 9-part ProjectBrief. This is what
 * replaces `deckProjectBrief.ts`'s hand-written `generateDeckProjectBrief`:
 * every Deck-specific rule becomes playbook DATA (derivedLines,
 * calculatedFields, alwaysIncludeLines...), interpreted here generically.
 */
import {
  NOT_SURE_VALUE,
  type AnswerValue,
  type Answers,
  type InspirationHypothesisKey,
  type InspirationPhotoAnswer,
} from "../schema/answers";
import type { BriefLine, BriefLineSource, ConfidenceLabel, ProjectBrief } from "../schema/brief";
import type { BriefSectionKey, PlaybookField, PlaybookSchema } from "../schema/playbook";
import { evaluateConditionGroup } from "./conditions";
import { evaluatePlaybookConsistency } from "./consistency";
import { computeVisibleSteps, validateField } from "./validation";

export interface MissionLike {
  name: string;
  objective?: string | null;
}

function isBlank(value: AnswerValue | undefined): boolean {
  return value === undefined || value === "" || (Array.isArray(value) && value.length === 0);
}

function optionLabel(field: PlaybookField, raw: string): string {
  if ("options" in field) {
    const opt = field.options.find((o) => o.value === raw);
    // `briefLabel` quand le Playbook en déclare un : une option formulée pour
    // répondre à une question ne se lit pas toujours dans un énoncé.
    if (opt) return opt.briefLabel ?? opt.label;
  }
  if (field.type === "budget" && field.ranges) {
    const range = field.ranges.find((r) => r.value === raw);
    if (range) return range.label;
  }
  return raw;
}

/**
 * `format` governs how a list is joined. It deliberately no longer governs
 * whether an option resolves to its label — that is now unconditional.
 *
 * It used to. `briefMapping.format` defaults to "raw", so any field whose
 * Playbook did not explicitly ask for "option_label" put its stored value into
 * the Dossier verbatim: a contractor opening the document before a sales call
 * read `garden_ground_level`, `composite_timber` and `7_000_15_000`. The
 * visitor's own review screen was correct, because it goes through
 * formatAnswerForDisplay, which always asked for labels — so the person who
 * typed the answers saw words and the person paying for the product saw
 * database rows.
 *
 * Resolving unconditionally is safe: optionLabel returns the value untouched
 * when the field has no matching option, so text, number and date fields are
 * unaffected. Fixing it here rather than in the schema default is what makes
 * it reach Missions that are already published — a Playbook snapshot is frozen
 * at publish time and would carry the old default forever, but the brief is
 * generated by this code at submit time.
 */
function formatValue(
  field: PlaybookField,
  value: AnswerValue,
  format: "raw" | "join_comma" | "option_label",
): string {
  void format;
  if (Array.isArray(value)) {
    const parts = value.map((v) => {
      if (typeof v === "string") return optionLabel(field, v);
      if (v && typeof v === "object" && "filename" in v)
        return String((v as { filename: unknown }).filename);
      return String(v);
    });
    return parts.join(", ");
  }
  if (typeof value === "string") return optionLabel(field, value);
  if (typeof value === "object" && value !== null) {
    return Object.values(value as Record<string, unknown>)
      .filter((v): v is string => typeof v === "string" && v.trim().length > 0)
      .join(" ");
  }
  return String(value);
}

/**
 * One answer, rendered the way a person should read it: option values
 * resolved to their labels, lists joined, address parts run together. The
 * review screen shows the visitor what they are about to send, and it has to
 * agree with the Dossier the sales team will read — so both go through this
 * same formatter rather than each inventing its own.
 */
export function formatAnswerForDisplay(field: PlaybookField, value: AnswerValue): string {
  if (isBlank(value)) return "";
  if (value === NOT_SURE_VALUE) return "Not sure";
  return formatValue(field, value, "option_label");
}

function interpolate(template: string, tokens: Record<string, string>): string {
  return template.replace(
    /\{\{\s*([a-zA-Z0-9_]+)(\|lower)?\s*\}\}/g,
    (_match, key: string, lowerFlag?: string) => {
      const raw = tokens[key] ?? "";
      return lowerFlag ? raw.toLowerCase() : raw;
    },
  );
}

function buildTokens(
  allFields: PlaybookField[],
  answers: Answers,
  calculated: Record<string, string>,
): Record<string, string> {
  const tokens: Record<string, string> = { ...calculated };
  for (const field of allFields) {
    const value = answers[field.key];
    if (value === undefined || value === NOT_SURE_VALUE) continue;
    tokens[field.key] = formatValue(field, value, "raw");
  }
  return tokens;
}

export function generateProjectBrief(
  schema: PlaybookSchema,
  answers: Answers,
  mission: MissionLike,
  generatedAt: string = new Date().toISOString(),
): ProjectBrief {
  const sections: Record<BriefSectionKey, BriefLine[]> = {
    confirmedInformation: [],
    assumptionsAndCalculated: [],
    constraints: [],
    missingInformation: [],
    budgetAndTiming: [],
  };

  const visibleSteps = computeVisibleSteps(schema, answers);
  const allVisibleFields = visibleSteps.flatMap((s) => s.visibleFields);

  // 1. Calculated fields (e.g. area = length * width), with fallback to a raw answer.
  const calculatedTokens: Record<string, string> = {};
  for (const calc of schema.briefConfig.calculatedFields) {
    let value: string | null = null;
    let source: BriefLineSource = "calculated_value";
    let targetSection = calc.section;

    if (calc.compute.op === "multiply") {
      const [aKey, bKey] = calc.compute.inputs;
      const a = Number.parseFloat(String(answers[aKey] ?? ""));
      const b = Number.parseFloat(String(answers[bKey] ?? ""));
      if (Number.isFinite(a) && Number.isFinite(b) && a > 0 && b > 0) {
        const rounded = Math.round(a * b);
        value = calc.compute.unit ? `${rounded} ${calc.compute.unit}` : String(rounded);
      }
    } else {
      const parts = calc.compute.inputs
        .map((k) => answers[k])
        .filter(
          (v): v is Exclude<AnswerValue, typeof NOT_SURE_VALUE> =>
            v !== undefined && v !== NOT_SURE_VALUE && String(v).trim() !== "",
        );
      if (parts.length > 0) value = parts.map(String).join(calc.compute.separator ?? " ");
    }

    if (value === null && calc.fallbackFieldKey) {
      const fallback = answers[calc.fallbackFieldKey];
      if (fallback !== undefined && fallback !== NOT_SURE_VALUE && String(fallback).trim() !== "") {
        value = String(fallback);
        source = "visitor_answer";
        targetSection = "confirmedInformation";
      }
    }

    if (value !== null) {
      calculatedTokens[calc.key] = value;
      sections[targetSection].push({
        label: calc.label,
        value,
        source,
        category: calc.category,
        fieldKey: calc.key,
      });
    } else if (calc.onMissingLabel) {
      sections.missingInformation.push({
        label: calc.onMissingLabel,
        value: calc.onMissingValue ?? "Not confirmed.",
        source: "deterministic_rule",
        fieldKey: calc.key,
      });
    }
  }

  const tokens = buildTokens(allVisibleFields, answers, calculatedTokens);

  // 2. Per-field brief mapping, plus "recommended but empty" -> missingInformation.
  for (const field of allVisibleFields) {
    const value = answers[field.key];
    const isNotSure = value === NOT_SURE_VALUE;
    const blank = isBlank(value);

    if ((blank || isNotSure) && field.desirability === "recommended") {
      sections.missingInformation.push({
        label: field.label,
        value: field.missingMessage ?? `${field.label} was not provided.`,
        source: "deterministic_rule",
        fieldKey: field.key,
      });
      continue;
    }
    if (blank || isNotSure || !field.briefMapping) continue;

    const mapping = field.briefMapping;
    const formatted = formatValue(field, value, mapping.format);
    if (!formatted && !mapping.includeIfEmpty) continue;
    sections[mapping.section].push({
      label: mapping.label,
      value: formatted,
      source: "visitor_answer",
      category: mapping.category,
      fieldKey: field.key,
    });
  }

  // 3. Inspiration-photo hypotheses: one BriefLine per non-empty dimension.
  // A dimension the visitor explicitly confirmed reads as a normal
  // visitor_answer in confirmedInformation; anything left unconfirmed stays
  // an image_hypothesis in assumptionsAndCalculated — never silently
  // promoted to a certainty (CLAUDE.md: the AI proposes, it never decides).
  for (const field of allVisibleFields) {
    if (field.type !== "inspiration_photo") continue;
    const value = answers[field.key];
    if (!value || typeof value !== "object" || !("hypotheses" in value)) continue;
    const answer = value as InspirationPhotoAnswer;
    const confirmed = answer.confirmed ?? {};

    const dimensions: { key: InspirationHypothesisKey; label: string; text?: string }[] = [
      { key: "style", label: "Style", text: answer.hypotheses.style },
      {
        key: "materials",
        label: "Materials",
        text:
          answer.hypotheses.materials.length > 0
            ? answer.hypotheses.materials.join(", ")
            : undefined,
      },
      { key: "shape", label: "Shape", text: answer.hypotheses.shape },
      {
        key: "elements",
        label: "Elements",
        text:
          answer.hypotheses.elements.length > 0 ? answer.hypotheses.elements.join(", ") : undefined,
      },
    ];

    for (const dimension of dimensions) {
      if (!dimension.text) continue;
      const isConfirmed = confirmed[dimension.key] === true;
      sections[isConfirmed ? "confirmedInformation" : "assumptionsAndCalculated"].push({
        label: dimension.label,
        value: dimension.text,
        source: isConfirmed ? "visitor_answer" : "image_hypothesis",
        category: "Inspiration",
        fieldKey: field.key,
      });
    }

    if (answer.suggestedQuestions.length > 0) {
      sections.missingInformation.push({
        label: "Questions to explore (from the inspiration photo)",
        value: answer.suggestedQuestions.join(" · "),
        source: "image_hypothesis",
        fieldKey: field.key,
      });
    }
  }

  // 4. Derived lines: playbook-authored conditional business rules.
  for (const rule of schema.briefConfig.derivedLines) {
    if (evaluateConditionGroup(rule.when, answers)) {
      sections[rule.section].push({
        label: rule.label,
        value: interpolate(rule.value, tokens),
        source: rule.source,
      });
    }
  }

  // 5. Always-injected caveats (e.g. "Permits not assessed").
  for (const line of schema.briefConfig.alwaysIncludeLines) {
    sections[line.section].push({
      label: line.label,
      value: line.value,
      source: "assumed_default",
      category: line.category,
    });
  }

  // 6. Project summary.
  const summaryParts = schema.briefConfig.summaryFragments
    .filter((f) => evaluateConditionGroup(f.when, answers))
    .map((f) => interpolate(f.template, tokens).trim())
    .filter(Boolean);
  const projectSummary =
    summaryParts.length > 0 ? summaryParts.join(" ") : schema.briefConfig.emptySummaryFallback;

  // 7. Confidence — a generic, engine-level heuristic (not playbook-configurable).
  const recommendedFields = allVisibleFields.filter((f) => f.desirability === "recommended");
  const requiredFields = allVisibleFields.filter((f) => f.desirability === "required");
  const emptyRecommendedCount = recommendedFields.filter(
    (f) => isBlank(answers[f.key]) || answers[f.key] === NOT_SURE_VALUE,
  ).length;
  const notSureRequiredCount = requiredFields.filter(
    (f) => answers[f.key] === NOT_SURE_VALUE,
  ).length;
  // The Vérificateur's own findings. Only warnings can reach this point — an
  // error-severity rule blocks the submit that would have produced this brief.
  const triggeredWarnings = evaluatePlaybookConsistency(schema, answers).warnings;
  const score = Math.max(
    0,
    Math.min(
      100,
      100 - emptyRecommendedCount * 10 - notSureRequiredCount * 15 - triggeredWarnings.length * 15,
    ),
  );
  const label: ConfidenceLabel = score >= 80 ? "high" : score >= 50 ? "medium" : "low";
  const reasons: string[] = [];
  if (emptyRecommendedCount > 0)
    reasons.push(`${emptyRecommendedCount} recommended field(s) not answered.`);
  if (notSureRequiredCount > 0)
    reasons.push(`${notSureRequiredCount} required field(s) answered "not sure".`);
  // The rule's own message, not a count of them: "2 consistency warning(s)
  // triggered" tells the sales team nothing they can act on, while the
  // sentence the trade expert wrote is exactly what to raise on the first call.
  for (const rule of triggeredWarnings) reasons.push(rule.message);

  // 8. Suggested next action: first conditional match wins, the unconditional entry is the default.
  const matchedAction =
    schema.briefConfig.suggestedNextActions.find(
      (a) => a.when && evaluateConditionGroup(a.when, answers),
    ) ?? schema.briefConfig.suggestedNextActions.find((a) => !a.when);
  const suggestedNextAction: BriefLine = {
    label: "Suggested next action",
    value: matchedAction?.value ?? "Review this project with the visitor directly.",
    source: "assumed_default",
  };

  return {
    generatedAt,
    missionName: schema.briefConfig.missionNameTemplate
      ? interpolate(schema.briefConfig.missionNameTemplate, tokens)
      : mission.name,
    status: schema.briefConfig.statusLabel ?? "ready",
    projectSummary,
    confirmedInformation: sections.confirmedInformation,
    assumptionsAndCalculated: sections.assumptionsAndCalculated,
    constraints: sections.constraints,
    missingInformation: sections.missingInformation,
    budgetAndTiming: sections.budgetAndTiming,
    confidence: { score, label, reasons },
    suggestedNextAction,
  };
}

